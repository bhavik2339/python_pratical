a=10
b=20

#arithmetic operator
print("addition is=",a+b)

#relational operator
print("a > b is=",a>b)
print("a < b is=",a<b)

#assignment operator
x=20
print("initial x=",x)
x+=5
print("final x=",x)

#logical operator
a=True
b=False
print("a and b is:",a and b)
print("a or b is:",a or b)
print("a and b is:",not b)

#bitwise operator
n=3
r=5
print("n & r is:",n & r)
print("n || r is:",n|r)
print("n ^ r is:",n^r)
print("~ r is:",~r)

